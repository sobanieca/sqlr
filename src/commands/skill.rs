use super::HELP_TEXT;
use crate::logger;
use crate::storage::home_dir;
use std::path::{Path, PathBuf};

const SKILL_TEMPLATE: &str = include_str!("../templates/SKILL.md");
const AGENT_INSTRUCTIONS: &str = include_str!("../templates/agent-instructions.txt");
const SKILL_TARGETS: &[(&str, &str)] = &[
    (".agents/skills", "Codex, Cursor"),
    (".claude/skills", "Claude Code, Cursor"),
];

pub fn execute(init: bool, connection: Option<String>) -> Result<(), String> {
    if init {
        return create_skill(connection.as_deref());
    }
    logger::print_line(AGENT_INSTRUCTIONS);
    logger::print_line(HELP_TEXT);
    Ok(())
}

fn skill_content(connection: Option<&str>) -> String {
    let (name, target, select) = match connection {
        Some(connection) => (
            format!("sqlr-{connection}"),
            format!("the `{connection}` database"),
            format!(
                "2. Run `sqlr set {connection}` first so every command targets this\n   connection."
            ),
        ),
        None => (
            "sqlr".to_string(),
            "a database".to_string(),
            "2. `sqlr ls` lists connections, the default is marked. Switch with\n   `sqlr set <name>`."
                .to_string(),
        ),
    };
    SKILL_TEMPLATE
        .replace("${name}", &name)
        .replace("${target}", &target)
        .replace("${select}", &select)
}

/// Marks a skill file written by `sqlr skill --init`. The rest of the marker
/// holds the arguments (`-n <connection>`), so `sqlr update` can write the
/// same skill again. It rewrites only the files that still have the marker.
const MARKER: &str = "<!-- Generated by `sqlr skill --init";

/// The skill with the marker line right after the front matter, where agents
/// still read the front matter.
fn generated_skill(connection: Option<&str>) -> String {
    let content = skill_content(connection);
    let args = connection.map(|c| format!(" -n {c}")).unwrap_or_default();
    let marker = format!(
        "{MARKER}{args}`. `sqlr update` rewrites this file; delete this line to keep your own changes. -->\n"
    );
    match content
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n"))
    {
        Some(end) => {
            let split = "---\n".len() + end + "\n---\n".len();
            format!("{}{marker}{}", &content[..split], &content[split..])
        }
        None => format!("{marker}{content}"),
    }
}

/// The connection of a generated skill: `None` when the file has no marker,
/// `Some(None)` for `/sqlr`, `Some(Some(name))` for `/sqlr-<name>`.
fn generated_connection(text: &str) -> Option<Option<String>> {
    let line = text.lines().find_map(|line| line.strip_prefix(MARKER))?;
    let args = line.split('`').next().unwrap_or_default().trim();
    Some(
        args.strip_prefix("-n ")
            .map(|name| name.trim().to_string())
            .filter(|name| !name.is_empty()),
    )
}

fn skill_name(connection: Option<&str>) -> String {
    match connection {
        Some(connection) => format!("sqlr-{connection}"),
        None => "sqlr".to_string(),
    }
}

/// The sqlr skill files under `root`: `/sqlr` and every `/sqlr-<name>`.
fn skill_files_in(root: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    for (dir, _) in SKILL_TARGETS {
        let Ok(entries) = std::fs::read_dir(root.join(dir)) else {
            continue;
        };
        let mut names: Vec<String> = entries
            .filter_map(Result::ok)
            .map(|entry| entry.file_name().to_string_lossy().to_string())
            .filter(|name| name == "sqlr" || name.starts_with("sqlr-"))
            .collect();
        names.sort();
        files.extend(
            names
                .into_iter()
                .map(|name| root.join(dir).join(name).join("SKILL.md"))
                .filter(|file| file.is_file()),
        );
    }
    files
}

/// The git root around `start` (searched up to the home directory).
fn git_root(start: &Path, home: Option<&Path>) -> Option<PathBuf> {
    let mut dir = start;
    loop {
        if dir.join(".git").exists() {
            return Some(dir.to_path_buf());
        }
        if Some(dir) == home {
            return None;
        }
        dir = dir.parent()?;
    }
}

struct SkillRoot {
    dir: PathBuf,
    global: bool,
}

/// Inside a git repository (searched from cwd up to the home directory): the
/// git root. Outside a repository: the home directory.
fn find_skill_root() -> Result<SkillRoot, String> {
    let home = home_dir().map(PathBuf::from);
    let cwd = std::env::current_dir().unwrap_or_default();
    if let Some(dir) = git_root(&cwd, home.as_deref()) {
        return Ok(SkillRoot { dir, global: false });
    }
    let home =
        home.ok_or("Not in a git repository and the home directory is unknown (set HOME).")?;
    Ok(SkillRoot {
        dir: home,
        global: true,
    })
}

fn write_skill(file: &Path, content: &str) -> Result<(), String> {
    if let Some(parent) = file.parent() {
        std::fs::create_dir_all(parent).map_err(|err| format!("{}: {err}", parent.display()))?;
    }
    std::fs::write(file, content).map_err(|err| format!("{}: {err}", file.display()))
}

/// `sqlr skill --init`: writes the skill, replacing the files when they exist.
fn create_skill(connection: Option<&str>) -> Result<(), String> {
    let skill_name = skill_name(connection);
    let root = find_skill_root()?;
    let content = generated_skill(connection);
    let mut written = Vec::new();
    for (dir, read_by) in SKILL_TARGETS {
        let path = Path::new(dir).join(&skill_name).join("SKILL.md");
        let file = root.dir.join(&path);
        let action = if file.exists() { "Updated" } else { "Created" };
        write_skill(&file, &content)?;
        written.push(format!("{action} {}  ({read_by})", path.display()));
    }

    if root.global {
        logger::info(format!(
            "Not in a git repository - installing for all projects in {}",
            root.dir.display()
        ));
    } else {
        logger::info(format!("Project root: {} (git root)", root.dir.display()));
    }
    for line in &written {
        logger::info(line);
    }
    logger::info("");
    logger::info(format!(
        "Try: /{skill_name} how many users signed up this week"
    ));
    Ok(())
}

/// The sqlr skill files under `root` that still have the marker, with their
/// connection.
fn generated_files(root: &Path) -> Vec<(PathBuf, Option<String>)> {
    skill_files_in(root)
        .into_iter()
        .filter_map(|file| {
            let text = std::fs::read_to_string(&file).ok()?;
            Some((file, generated_connection(&text)?))
        })
        .collect()
}

/// Rewrites the skills that `sqlr skill --init` wrote, when they still have
/// the marker: the ones at the git root of the current directory, else (no
/// repository, or no generated skill in it) the ones in the home directory.
/// Prints the files it changed. `sqlr update` runs it with the new binary
/// (`sqlr skill --refresh`), so the new skill text is written.
pub fn refresh() {
    let home = home_dir().map(PathBuf::from);
    let cwd = std::env::current_dir().unwrap_or_default();
    let files = git_root(&cwd, home.as_deref())
        .map(|root| generated_files(&root))
        .filter(|files| !files.is_empty())
        .or_else(|| home.as_deref().map(generated_files))
        .unwrap_or_default();

    let mut updated = Vec::new();
    for (file, connection) in files {
        let content = generated_skill(connection.as_deref());
        if std::fs::read_to_string(&file).is_ok_and(|text| text == content) {
            continue;
        }
        match std::fs::write(&file, &content) {
            Ok(()) => updated.push(file),
            Err(err) => logger::error(format!(
                "Failed to update the skill {}: {err}",
                file.display()
            )),
        }
    }
    if !updated.is_empty() {
        logger::info("Updated skills:");
        for file in &updated {
            logger::info(format!("  {}", file.display()));
        }
    }
}
